const dictionaries: Record<Language, Dictionary> = { en, kn }

type I18nValue = string | number

type I18nContextValue = {
  language: Language
  locale: 'en-IN' | 'kn-IN'
  setLanguage: (language: Language) => void
  t: (key: string, params?: Record<string, I18nValue>) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem('tuberintel-language')
    return saved === 'kn' ? 'kn' : 'en'
  })

  const setLanguage = (next: Language) => {
    localStorage.setItem('tuberintel-language', next)
    document.documentElement.lang = next === 'kn' ? 'kn' : 'en-IN'
    setLanguageState(next)
  }

  const value = useMemo<I18nContextValue>(() => ({
    language,
    locale: language === 'kn' ? 'kn-IN' : 'en-IN',
    setLanguage,
    t: (key, params = {}) => {
      const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key
      return Object.entries(params).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template)
    },
  }), [language])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
